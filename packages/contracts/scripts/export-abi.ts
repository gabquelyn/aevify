/**
 * Copy the compiled AevifyCheckout ABI into @aevify/shared so the web app and listener
 * get a fully typed ABI. Run after changing the contract:
 *
 *   docker compose run --rm contracts npm run export-abi
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifactPath = path.join(here, "../artifacts/contracts/AevifyCheckout.sol/AevifyCheckout.json");
const outPath = path.join(here, "../../shared/src/abi/aevify-checkout.ts");

const artifact = JSON.parse(await readFile(artifactPath, "utf8")) as { abi: unknown };
const source = `// Generated by packages/contracts/scripts/export-abi.ts. Do not edit by hand.
export const aevifyCheckoutAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
await writeFile(outPath, source);
console.log(`Wrote ${path.relative(process.cwd(), outPath)}`);
